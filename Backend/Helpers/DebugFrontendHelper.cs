using System.Diagnostics;
using System.Runtime.InteropServices;

namespace Backend.Helpers
{
    /// <summary>
    /// Launches the frontend dev server alongside the backend during development.
    /// </summary>
    public class DebugFrontendHelper : IDisposable
    {
        Process? DevProcess;

        public static string FrontendPath
        {
            get
            {
                var currentDir = Directory.GetCurrentDirectory();
                var frontendPath = Path.Combine(currentDir, "..", "Frontend");
                return Path.GetFullPath(frontendPath);
            }
        }

        public static string? NodePath
        {
            get
            {
                var pathEnv = Environment.GetEnvironmentVariable("PATH");
                if (string.IsNullOrWhiteSpace(pathEnv))
                    return null;

                var paths = pathEnv.Split(Path.PathSeparator);

                if (RuntimeInformation.IsOSPlatform(OSPlatform.Windows))
                {
                    var pathext = (Environment.GetEnvironmentVariable("PATHEXT") ?? ".EXE;.CMD;.BAT;.COM")
                        .Split(';', StringSplitOptions.RemoveEmptyEntries);

                    foreach (var dir in paths)
                    {
                        foreach (var ext in pathext)
                        {
                            var candidate = Path.Combine(dir.Trim(), "node" + ext.ToLower());
                            if (File.Exists(candidate))
                                return Path.GetFullPath(candidate);
                        }
                    }
                }
                else
                {
                    foreach (var dir in paths)
                    {
                        var candidate = Path.Combine(dir.Trim(), "node");
                        if (File.Exists(candidate))
                            return Path.GetFullPath(candidate);
                    }
                }

                return null;
            }
        }

        public static async Task Start(string backendURL)
        {
            var helper = new DebugFrontendHelper();
            CopyBackendConfigToFrontend(backendURL);
            await helper.NpmRunDev();
        }

        public static async void CopyBackendConfigToFrontend(string backendURL)
        {
            var basePath = Path.Combine(FrontendPath, "src", "lib");
            if (!Directory.Exists(basePath)) basePath = FrontendPath;

            var filePath = Path.Combine(basePath, "backend-config.ts");
            var debugScript = "// This file is auto generated by the backend, and will point the frontend to the correct API host (do not edit)\n";
            debugScript += $"const lastDebugBackendURL = `{backendURL}`;\n";
            debugScript += "export { lastDebugBackendURL };\n";

            File.WriteAllText(filePath, debugScript);
        }

        /// <summary>
        /// Runs the Vite dev server so it launches alongside the backend with a single click.
        /// </summary>
        public async Task NpmRunDev()
        {
            var psi = new ProcessStartInfo()
            {
                WorkingDirectory = FrontendPath,
                FileName = NodePath,
                Arguments = $"run_dev.js {Process.GetCurrentProcess().Id}",
                CreateNoWindow = false,
                UseShellExecute = false,
            };

            DevProcess = Process.Start(psi);
            DevProcess?.WaitForExitAsync();
        }

        public void Dispose()
        {
            if (DevProcess != null && !DevProcess.HasExited)
            {
                DevProcess.Kill();
            }
        }
    }
}
